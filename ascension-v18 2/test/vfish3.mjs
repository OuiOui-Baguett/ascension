import { launch } from './_browser.mjs';
const b = await launch();
const page = await b.newPage({ viewport: { width: 390, height: 844 } });
const errs = []; page.on('pageerror', e => errs.push('JS: ' + e.message));
const tap = async sel => { const el = await page.$(sel); if (!el) throw new Error(sel); await el.evaluate(e => e.click()); };
const walk = async (key, ms) => { await page.keyboard.down(key); await page.waitForTimeout(ms); await page.keyboard.up(key); await page.waitForTimeout(700); };
const dbg = () => page.evaluate(() => window.__fish && window.__fish());
await page.goto('http://localhost:2567/?quality=high');
await page.waitForFunction(() => !!document.querySelector('#gamepick'), null, { timeout: 20000 });
await tap('.gcard[data-g="fish"]'); await page.fill('#name', 'QUENTIN'); await tap('#create');
await page.waitForFunction(() => !!document.querySelector('#start'), null, { timeout: 15000 });
await tap('#start'); await page.waitForTimeout(9000);
console.log('départ  ', JSON.stringify(await dbg()));
await page.keyboard.down('ArrowDown');
for (let i=0;i<5;i++){ await page.waitForTimeout(600); console.log('  pendant', JSON.stringify(await dbg())); }
await page.keyboard.up('ArrowDown'); await page.waitForTimeout(700); console.log('plage   ', JSON.stringify(await dbg()));
await page.screenshot({ path: '/tmp/shots/a-plage.png' });
await walk('ArrowUp', 6000); console.log('ponton  ', JSON.stringify(await dbg()));
await page.screenshot({ path: '/tmp/shots/b-ponton.png' });
console.log('barre   ', await page.evaluate(() => (document.querySelector('.actionbar, .hint')||{}).textContent));
console.log('erreurs :', errs.length ? errs : 'aucune');
await b.close();
